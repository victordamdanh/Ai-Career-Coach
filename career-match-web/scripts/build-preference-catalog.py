"""Build the suggestion data from the O*NET reported-titles CSV and Census places ZIP."""

import argparse
import base64
import csv
import gzip
import io
import json
import re
import textwrap
from pathlib import Path
from zipfile import ZipFile


def reported_titles(path):
    with path.open(encoding="utf-8-sig", newline="") as source:
        titles = (row["Reported Job Title"].strip() for row in csv.DictReader(source))
        return sorted({title for title in titles if title and len(title) <= 90}, key=str.casefold)


def census_places(path):
    suffix = re.compile(
        r" (?:city and borough|city and county|city|town|village|borough|municipality|CDP|comunidad|zona urbana)$"
    )
    with ZipFile(path) as archive:
        member = next(name for name in archive.namelist() if name.endswith(".txt"))
        with archive.open(member) as source:
            rows = csv.DictReader(io.TextIOWrapper(source, encoding="utf-8-sig"), delimiter="|")
            return sorted({f"{suffix.sub('', row['NAME'].strip())}, {row['USPS']}" for row in rows}, key=str.casefold)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("titles", type=Path)
    parser.add_argument("places", type=Path)
    args = parser.parse_args()
    titles = reported_titles(args.titles)
    places = census_places(args.places)
    packed = gzip.compress(json.dumps([titles, places], ensure_ascii=False, separators=(",", ":")).encode(), mtime=0)
    lines = textwrap.wrap(base64.b64encode(packed).decode(), 120)
    output = Path(__file__).resolve().parent.parent / "web" / "preference-catalog.mjs"
    output.write_text("// Generated by scripts/build-preference-catalog.py. Source credits in README.md.\n"
                      "export const catalog = [\n" + "".join(f'  "{line}",\n' for line in lines) + "].join(\"\");\n")
    print(f"Wrote {len(titles):,} titles and {len(places):,} places to {output.name}.")


if __name__ == "__main__":
    main()
